#!/usr/bin/env python3
"""Regenerate every Purandara icon and logo from one geometry.

The mark (docs/branding.md): five gold steps rising to a cream dot, the upper
Sa: an arohanam, the first thing a student sings. Run from the repository
root:

    python3 tools/brand/build.py

Standard library only, plus `rsvg-convert` (librsvg: `brew install librsvg`)
for the PNGs. The wordmark and tagline are fixed outlines in this folder
(Rozha One and Mukta, SIL OFL 1.1), so no font is needed at build time.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = ROOT / "tools/brand"

# Palette (docs/branding.md). The app's Compose theme, the iOS accent colour
# and the site's CSS use the same values.
MAROON = "#7A1F2B"
MAROON_LIGHT = "#8F2A37"
MAROON_DEEP = "#521523"
GOLD = "#C8962E"
GOLD_LIGHT = "#E8C163"
CREAM = "#FFF8EE"
NIGHT = "#1E0A0F"
NIGHT_LIGHT = "#3A121B"

# --- The mark, in a 1024 design space -------------------------------------

STEPS = 5
STEP = 96
STROKE = 60
START = (250, 770)
TAIL = 40
DOT_R = 52
DOT_OFFSET = (120, -70)  # from the top of the last riser


def _step_points() -> list[tuple[int, int]]:
    x, y = START
    points = [(x, y)]
    for _ in range(STEPS):
        x += STEP
        points.append((x, y))
        y -= STEP
        points.append((x, y))
    points.append((x + TAIL, y))
    return points


POINTS = _step_points()
DOT = (POINTS[-2][0] + DOT_OFFSET[0], POINTS[-2][1] + DOT_OFFSET[1])
STEPS_D = "M" + " L".join(f"{x},{y}" for x, y in POINTS)
DOT_D = f"M{DOT[0] - DOT_R},{DOT[1]} a{DOT_R},{DOT_R} 0 1,0 {2 * DOT_R},0 a{DOT_R},{DOT_R} 0 1,0 {-2 * DOT_R},0 Z"

# Bounding box including the round caps and the dot, and its centre.
_half = STROKE / 2
BBOX = (
    min(x for x, _ in POINTS) - _half,
    min(min(y for _, y in POINTS) - _half, DOT[1] - DOT_R),
    max(max(x for x, _ in POINTS) + _half, DOT[0] + DOT_R),
    max(y for _, y in POINTS) + _half,
)
CENTRE = ((BBOX[0] + BBOX[2]) / 2, (BBOX[1] + BBOX[3]) / 2)
# Furthest point of the mark from its centre: what must fit a circular mask.
RADIUS = max(
    ((DOT[0] - CENTRE[0]) ** 2 + (DOT[1] - CENTRE[1]) ** 2) ** 0.5 + DOT_R,
    max(((x - CENTRE[0]) ** 2 + (y - CENTRE[1]) ** 2) ** 0.5 for x, y in POINTS) + _half,
)


def mark_group(size: float, cx: float, cy: float, steps: str, dot: str) -> str:
    """The mark scaled so its bounding box is `size` wide, centred on (cx, cy)."""
    scale = size / (BBOX[2] - BBOX[0])
    return (
        f'<g transform="translate({cx:.2f} {cy:.2f}) scale({scale:.5f}) translate({-CENTRE[0]:.2f} {-CENTRE[1]:.2f})">'
        f'<path d="{STEPS_D}" fill="none" stroke="{steps}" stroke-width="{STROKE}" '
        'stroke-linecap="round" stroke-linejoin="round"/>'
        f'<path d="{DOT_D}" fill="{dot}"/></g>'
    )


GOLD_GRADIENT = (
    f'<linearGradient id="gold" gradientUnits="userSpaceOnUse" x1="{BBOX[0]}" y1="{BBOX[1]}" x2="{BBOX[2]}" y2="{BBOX[3]}">'
    f'<stop offset="0" stop-color="{GOLD_LIGHT}"/><stop offset="1" stop-color="{GOLD}"/></linearGradient>'
)


def background(top: str, mid: str, deep: str, rx: float = 0) -> str:
    return (
        '<radialGradient id="bg" cx="0.35" cy="0.25" r="0.9">'
        f'<stop offset="0" stop-color="{top}"/><stop offset="0.6" stop-color="{mid}"/>'
        f'<stop offset="1" stop-color="{deep}"/></radialGradient>'
    ), f'<rect width="1024" height="1024" rx="{rx}" fill="url(#bg)"/>'


def svg(body: str, defs: str = "", w: int = 1024, h: int = 1024, comment: str = "") -> str:
    note = f"<!-- {comment} -->\n" if comment else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}">\n{note}'
        f"<defs>{defs}</defs>{body}</svg>\n"
    )


# Icon glyph sizes (bounding-box width as a share of the canvas).
ICON_SIZE = 0.66 * 1024  # iOS: the system masks a full-bleed square
FAVICON_SIZE = 0.70 * 1024

GENERATED = "Generated by tools/brand/build.py; edit that script, not this file."


def icon_svg(variant: str = "light", rx: float = 0) -> str:
    if variant == "light":
        bg_defs, bg = background(MAROON_LIGHT, MAROON, MAROON_DEEP, rx)
        return svg(bg + mark_group(ICON_SIZE, 512, 512, "url(#gold)", CREAM), bg_defs + GOLD_GRADIENT)
    if variant == "dark":
        bg_defs, bg = background(NIGHT_LIGHT, NIGHT, "#0E0407", rx)
        return svg(bg + mark_group(ICON_SIZE, 512, 512, "url(#gold)", CREAM), bg_defs + GOLD_GRADIENT)
    # tinted: a grayscale glyph on black; iOS applies the user's tint
    return svg('<rect width="1024" height="1024" fill="#000"/>' + mark_group(ICON_SIZE, 512, 512, "#C8C8C8", "#FFFFFF"))


# --- Text outlines -----------------------------------------------------------


def outline(name: str) -> tuple[list[float], str]:
    text = (HERE / f"{name}.svg").read_text()
    box = [float(v) for v in re.search(r'viewBox="([^"]+)"', text).group(1).split()]
    return box, re.search(r' d="([^"]+)"', text).group(1)


def placed(name: str, x: float, y: float, height: float, fill: str) -> str:
    """Text outline with its bounding box's top-left at (x, y), `height` tall."""
    (bx, by, bw, bh), d = outline(name)
    s = height / bh
    return f'<path transform="translate({x:.1f} {y:.1f}) scale({s:.5f}) translate({-bx} {-by})" fill="{fill}" d="{d}"/>'


def text_width(name: str, height: float) -> float:
    (_, _, bw, bh), _ = outline(name)
    return bw * height / bh


# --- Android -----------------------------------------------------------------

ANDROID_RES = ROOT / "app/src/main/res"
# Adaptive icons: 108dp layers; only a 66dp circle is sure to show.
ADAPTIVE_SAFE_RADIUS = 33 * 1024 / 108


def android_mark_layer(steps_color: str | None, dot_color: str) -> str:
    scale = ADAPTIVE_SAFE_RADIUS / RADIUS * 108 / 1024
    if steps_color is None:  # gold gradient
        stroke = (
            '<aapt:attr name="android:strokeColor"><gradient android:type="linear" '
            f'android:startX="{BBOX[0]}" android:startY="{BBOX[1]}" android:endX="{BBOX[2]}" android:endY="{BBOX[3]}" '
            f'android:startColor="{GOLD_LIGHT}" android:endColor="{GOLD}"/></aapt:attr>'
        )
        stroke_attr = ""
    else:
        stroke, stroke_attr = "", f' android:strokeColor="{steps_color}"'
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} The Arohanam mark (docs/branding.md). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:translateX="54" android:translateY="54" android:scaleX="{scale:.6f}" android:scaleY="{scale:.6f}">
        <group android:translateX="{-CENTRE[0]:.2f}" android:translateY="{-CENTRE[1]:.2f}">
            <path
                android:pathData="{STEPS_D}"
                android:fillColor="#00000000"{stroke_attr}
                android:strokeWidth="{STROKE}"
                android:strokeLineCap="round"
                android:strokeLineJoin="round">{stroke}</path>
            <path
                android:pathData="{DOT_D}"
                android:fillColor="{dot_color}" />
        </group>
    </group>
</vector>
'''


def android_background() -> str:
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="38" android:centerY="27" android:gradientRadius="97"
                android:startColor="{MAROON_LIGHT}" android:centerColor="{MAROON}" android:endColor="{MAROON_DEEP}" />
        </aapt:attr>
    </path>
</vector>
'''


def write_android() -> None:
    drawable = ANDROID_RES / "drawable"
    (drawable / "ic_launcher_foreground.xml").write_text(android_mark_layer(None, CREAM))
    (drawable / "ic_launcher_monochrome.xml").write_text(android_mark_layer("#FFFFFF", "#FFFFFF"))
    (drawable / "ic_launcher_background.xml").write_text(android_background())
    (ANDROID_RES / "mipmap-anydpi-v26/ic_launcher.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {GENERATED} -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''')


# --- iOS -----------------------------------------------------------------------

IOS_ICONS = ROOT / "iosApp/Purandara/Assets.xcassets/AppIcon.appiconset"


def render(svg_text: str, out: Path, width: int, height: int | None = None) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    args = ["rsvg-convert", "-w", str(width)] + (["-h", str(height)] if height else []) + ["-o", str(out)]
    subprocess.run(args, input=svg_text.encode(), check=True)


def write_ios() -> None:
    images = []
    for variant, appearance in (("light", None), ("dark", "dark"), ("tinted", "tinted")):
        name = f"AppIcon-{variant}.png"
        render(icon_svg(variant), IOS_ICONS / name, 1024)
        entry = {"filename": name, "idiom": "universal", "platform": "ios", "size": "1024x1024"}
        if appearance:
            entry["appearances"] = [{"appearance": "luminosity", "value": appearance}]
        images.append(entry)
    (IOS_ICONS / "Contents.json").write_text(json.dumps({"images": images, "info": {"author": "xcode", "version": 1}}, indent=2) + "\n")


# --- Site and brand files ----------------------------------------------------------

SITE = ROOT / "site/static"


def lockup(mark_fill_steps: str, mark_fill_dot: str, text_fill: str, height: float = 200) -> tuple[str, float]:
    """Mark beside the wordmark; returns the SVG body and its width."""
    mark_w = height
    gap = height * 0.28
    word_h = height * 0.62
    word_w = text_width("wordmark", word_h)
    body = mark_group(mark_w, mark_w / 2, height / 2, mark_fill_steps, mark_fill_dot) + placed(
        "wordmark", mark_w + gap, (height - word_h) / 2 + height * 0.04, word_h, text_fill
    )
    return body, mark_w + gap + word_w


def write_site_and_brand() -> None:
    (SITE / "favicon.svg").write_text(icon_svg("light", rx=224).replace("<defs>", f"<!-- {GENERATED} -->\n<defs>", 1))
    render(icon_svg("light"), SITE / "apple-touch-icon.png", 180)
    # The masthead mark: gold steps and a cream dot, on the maroon bar.
    (SITE / "mark.svg").write_text(svg(mark_group(1024, 512, 512, GOLD_LIGHT, CREAM), comment=GENERATED))

    # Social-share card, 1200x630.
    bg_defs, _ = background(MAROON_LIGHT, MAROON, MAROON_DEEP)
    lock_h = 160
    body, width = lockup("url(#gold)", CREAM, CREAM, lock_h)
    tag_h = 36
    tag_w = text_width("tagline", tag_h)
    x0 = (1200 - width) / 2
    card = svg(
        '<rect width="1200" height="630" fill="url(#bg)"/>'
        f'<g transform="translate({x0:.1f} 190)">{body}</g>'
        + placed("tagline", (1200 - tag_w) / 2, 410, tag_h, "#E9D59A")
        + f'<rect x="0" y="618" width="1200" height="12" fill="{GOLD}"/>',
        bg_defs + GOLD_GRADIENT,
        1200,
        630,
    )
    render(card, SITE / "images/og.png", 1200, 630)

    # Lockups for documents (README, the brand guide): on light and on maroon.
    for name, steps, dot, text in (("lockup", MAROON, GOLD, MAROON), ("lockup-on-maroon", "url(#gold)", CREAM, CREAM)):
        body, width = lockup(steps, dot, text, 200)
        (HERE / f"{name}.svg").write_text(svg(body, GOLD_GRADIENT, round(width), 200, GENERATED))
    (HERE / "icon.svg").write_text(icon_svg("light").replace("<defs>", f"<!-- {GENERATED} -->\n<defs>", 1))
    render(icon_svg("light"), HERE / "icon-512.png", 512)  # store listings


def main() -> None:
    if not shutil.which("rsvg-convert"):
        raise SystemExit("rsvg-convert not found: brew install librsvg")
    write_android()
    write_ios()
    write_site_and_brand()
    print(f"mark centre {CENTRE}, radius {RADIUS:.0f}; wrote Android, iOS, site and tools/brand files")


if __name__ == "__main__":
    main()
